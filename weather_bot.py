import os
import json
import sys

def create_snapshot(target_dir, output_file):
    """Сканирует папку и создает снимок: относительный путь и размер файла."""
    if not os.path.exists(target_dir):
        print(f"\n❌ Ошибка: Папка '{target_dir}' не найдена!")
        return False
        
    print(f"\n🔍 Сканирую папку: {target_dir}...")
    snapshot = {}
    
    for root, dirs, files in os.walk(target_dir):
        for file in files:
            full_path = os.path.join(root, file)
            # Получаем путь относительно корня (например: "135 Травма.../001.mp3")
            rel_path = os.path.relpath(full_path, target_dir)
            try:
                file_size = os.path.getsize(full_path)
                snapshot[rel_path] = file_size
            except Exception:
                continue

    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(snapshot, f, ensure_ascii=False, indent=4)
    
    print(f"✅ Успешно! Снимок сохранен в: {output_file}")
    print(f"📊 Всего проиндексировано файлов: {len(snapshot)}")
    return True

def compare_snapshots(home_snapshot_file, studio_dir):
    """Сравнивает домашний снимок с реальной папкой на студии."""
    if not os.path.exists(home_snapshot_file):
        print(f"\n❌ Ошибка: Файл домашнего снимка '{home_snapshot_file}' не найден рядом с программой!")
        return
    if not os.path.exists(studio_dir):
        print(f"\n❌ Ошибка: Студийная папка '{studio_dir}' не найдена!")
        return

    print(f"\n📖 Загружаю домашний снимок...")
    with open(home_snapshot_file, 'r', encoding='utf-8') as f:
        home_data = json.load(f)

    print(f"🔍 Сканирую студийную папку: {studio_dir}...")
    studio_data = {}
    for root, dirs, files in os.walk(studio_dir):
        for file in files:
            full_path = os.path.join(root, file)
            rel_path = os.path.relpath(full_path, studio_dir)
            try:
                studio_data[rel_path] = os.path.getsize(full_path)
            except Exception:
                continue

    can_delete = []
    size_mismatch = []
    not_in_studio = []

    # Сверяем домашние файлы со студийными
    for rel_path, home_size in home_data.items():
        if rel_path in studio_data:
            if studio_data[rel_path] == home_size:
                can_delete.append(rel_path)
            else:
                size_mismatch.append((rel_path, home_size, studio_data[rel_path]))
        else:
            not_in_studio.append(rel_path)

    # Записываем отчет
    report_file = "отчет_сравнения.txt"
    with open(report_file, 'w', encoding='utf-8') as f:
        f.write("=== ЧТО МОЖНО БЕЗОПАСНО УДАЛИТЬ С ДОМАШНЕГО ПК (Уже есть в архиве на студии) ===\n")
        if can_delete:
            for item in sorted(can_delete):
                f.write(f"[ОК] {item}\n")
        else:
            f.write("Таких файлов нет.\n")

        f.write("\n=== ВНИМАНИЕ: СОВПАДАЕТ ИМЯ, НО ОТЛИЧАЕТСЯ РАЗМЕР (Проверьте вручную!) ===\n")
        if size_mismatch:
            for item, h_sz, s_sz in sorted(size_mismatch):
                f.write(f"[РАЗМЕР ОТЛИЧАЕТСЯ] {item} (Дом: {h_sz} байт, Студия: {s_sz} байт)\n")
        else:
            f.write("Таких файлов нет.\n")

        f.write("\n=== НАДО ПЕРЕНЕСТИ НА СТУДИЮ (Этих файлов нет в архиве) ===\n")
        if not_in_studio:
            for item in sorted(not_in_studio):
                f.write(f"[НЕТ В АРХИВЕ] {item}\n")
        else:
            f.write("Все домашние файлы уже есть в архиве!\n")

    print(f"\n🎉 Сравнение завершено!")
    print(f"🟢 Можно удалить дома: {len(can_delete)} файлов")
    print(f"🟡 Расхождение в размерах: {len(size_mismatch)} файлов")
    print(f"🔴 Нужно донести в архив: {len(not_in_studio)} файлов")
    print(f"💾 Подробный отчет сохранен в файл: {report_file}")

